import { basename } from "node:path";
import type {
  DatabaseOption,
  NewProjectConfiguration,
  PackageManager,
} from "./project-creation.ts";

export function nodePackageManager(packageManager: PackageManager) {
  if (["npm", "yarn", "bun"].includes(packageManager)) return packageManager;
  if (packageManager === "pnpm") return "pnpm";
  return "npm";
}

export function envExample(configuration: NewProjectConfiguration) {
  const lines = ["APP_URL=http://localhost:3000"];
  if (configuration.database !== "none") lines.push("DATABASE_URL=");
  if (configuration.advancedOptions.includes("auth"))
    lines.push("AUTH_SECRET=");
  return `${lines.join("\n")}\n`;
}

export function readme(configuration: NewProjectConfiguration, target: string) {
  const packageManager = nodePackageManager(configuration.packageManager);
  return [
    `# ${basename(target)}`,
    "",
    "Generated by Blame.",
    "",
    "## Development",
    "",
    `- Install: \`${packageManager} install\``,
    `- Dev server: \`${packageManager} run dev\``,
    `- Build: \`${packageManager} run build\``,
    "",
  ].join("\n");
}

export function dockerfile(configuration: NewProjectConfiguration) {
  const packageManager = nodePackageManager(configuration.packageManager);
  return [
    "FROM node:22-bookworm-slim",
    "WORKDIR /app",
    "COPY package.json ./",
    `RUN corepack enable && ${packageManager} install`,
    "COPY . .",
    `CMD [\"${packageManager}\", \"run\", \"dev\", \"--\", \"--host\", \"0.0.0.0\"]`,
    "",
  ].join("\n");
}

export function dockerCompose(configuration: NewProjectConfiguration) {
  const database = databaseService(configuration.database);
  const services = [
    "services:",
    "  app:",
    "    build: .",
    "    ports:",
    '      - "3000"',
    "    labels:",
    '      blame.preview: "true"',
    '      blame.preview.port: "3000"',
  ];

  if (database) services.push(...database);
  return `${services.join("\n")}\n`;
}

function databaseService(database: DatabaseOption) {
  if (database === "postgresql") {
    return [
      "  database:",
      "    image: postgres:17-alpine",
      "    environment:",
      "      POSTGRES_PASSWORD: blame",
      "      POSTGRES_DB: blame",
    ];
  }
  if (database === "mysql") {
    return [
      "  database:",
      "    image: mysql:9",
      "    environment:",
      "      MYSQL_ROOT_PASSWORD: blame",
      "      MYSQL_DATABASE: blame",
    ];
  }
  if (database === "mongodb") {
    return ["  database:", "    image: mongo:8"];
  }
  return undefined;
}

export function githubActions(configuration: NewProjectConfiguration) {
  const packageManager = nodePackageManager(configuration.packageManager);
  return [
    "name: CI",
    "on: [push, pull_request]",
    "jobs:",
    "  check:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v5",
    "      - uses: actions/setup-node@v5",
    "        with:",
    "          node-version: 22",
    `      - run: corepack enable && ${packageManager} install`,
    `      - run: ${packageManager} run build`,
    "",
  ].join("\n");
}

export function blamePreview(configuration: NewProjectConfiguration) {
  const port =
    configuration.frontend === "next" || configuration.frontend === "nuxt"
      ? 3000
      : 5173;
  return `${JSON.stringify({ command: "dev", port }, null, 2)}\n`;
}

